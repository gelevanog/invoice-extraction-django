# Only unambiguous-enough symbols; "$" defaults to USD and "kr" is deliberately absent.
CURRENCY_SYMBOLS: dict[str, str] = {"€": "EUR", "£": "GBP", "$": "USD", "¥": "JPY", "zł": "PLN"}


def is_iso_4217(code: str | None) -> bool:
    return code is not None and code.upper() in ISO_4217_CODES
